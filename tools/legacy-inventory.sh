#!/usr/bin/env bash
#
# Reproducible inventory of the legacy Java Pet Store 1.3.1_02 storefront.
#
# Prints a Markdown report to stdout describing the size of the code that ends
# up in petstore.ear and how much of it touches each J2EE API. This is how the
# migration surface was sized: the numbers can be regenerated and checked
# instead of trusted.
#
# usage: tools/legacy-inventory.sh <path-to-petstore1.3.1_02>
#
# The legacy distribution is not part of this repository; download it and pass
# its location as the argument.

set -euo pipefail

if [ $# -ne 1 ] || [ ! -d "$1/src/apps/petstore" ]; then
  echo "usage: $0 <path-to-petstore1.3.1_02>" >&2
  exit 2
fi

LEGACY="$(cd "$1" && pwd)"
SRC="$LEGACY/src"

# Components packaged into petstore.ear (see src/apps/petstore/src/build.xml).
IN_SCOPE_COMPONENTS="address asyncsender cart catalog contactinfo creditcard
customer encodingfilter lineitem purchaseorder servicelocator signon uidgen
util/tracer xmldocuments"

# Source trees that belong to the other applications.
OUT_OF_SCOPE="apps/admin apps/opc apps/supplier components/mailer
components/processmanager components/supplierpo webservices"

SCOPE_DIRS=("$SRC/apps/petstore/src" "$SRC/waf/src")
COMPONENT_DIRS=()
for c in $IN_SCOPE_COMPONENTS; do
  SCOPE_DIRS+=("$SRC/components/$c")
  COMPONENT_DIRS+=("$SRC/components/$c")
done

# count_files <name-glob> <dir>...
count_files() {
  local glob="$1"
  shift
  find "$@" -type f -name "$glob" 2>/dev/null | wc -l | tr -d ' '
}

# count_lines <name-glob> <dir>...
count_lines() {
  local glob="$1"
  shift
  { find "$@" -type f -name "$glob" -print0 2>/dev/null | xargs -0 cat 2>/dev/null || true; } |
    wc -l | tr -d ' '
}

# files_matching <extended-regex> : Java files in scope with a matching line
files_matching() {
  { grep -rlE --include='*.java' "$1" "${SCOPE_DIRS[@]}" 2>/dev/null || true; } |
    wc -l | tr -d ' '
}

# occurrences <extended-regex> <name-glob> <dir>... : matching lines
occurrences() {
  local regex="$1" glob="$2"
  shift 2
  { grep -rhE --include="$glob" "$regex" "$@" 2>/dev/null || true; } | wc -l | tr -d ' '
}

size_row() {
  local label="$1"
  shift
  printf '| %s | %s | %s |\n' "$label" "$(count_files '*.java' "$@")" "$(count_lines '*.java' "$@")"
}

api_row() {
  printf '| `%s` | %s |\n' "$1" "$(files_matching "^import[[:space:]]+($2)")"
}

kind_row() {
  printf '| %s | %s |\n' "$1" "$(files_matching "$2")"
}

echo "# Legacy inventory: Java Pet Store 1.3.1_02 storefront"
echo
echo "Generated by \`tools/legacy-inventory.sh\`. Do not edit by hand."
echo
echo "Scope: the source that is packaged into \`petstore.ear\`, that is"
echo "\`src/apps/petstore\`, \`src/waf\` and the components the storefront bundles."
echo

echo "## Java source in scope"
echo
echo "| Area | Files | Lines |"
echo "| --- | --- | --- |"
size_row "Storefront application (\`apps/petstore\`)" "$SRC/apps/petstore/src"
size_row "Web application framework (\`waf\`)" "$SRC/waf/src"
size_row "Bundled components" "${COMPONENT_DIRS[@]}"
size_row "**Total in scope**" "${SCOPE_DIRS[@]}"
size_row "Whole distribution (\`src\`), for comparison" "$SRC"
echo

echo "## Java source per bundled component"
echo
echo "| Component | Files | Lines |"
echo "| --- | --- | --- |"
for c in $IN_SCOPE_COMPONENTS; do
  size_row "\`$c\`" "$SRC/components/$c"
done
echo

echo "## Pages"
echo
DOCROOT="$SRC/apps/petstore/src/docroot"
echo "| Set | JSP files | Lines |"
echo "| --- | --- | --- |"
printf '| English (docroot root) | %s | %s |\n' \
  "$(find "$DOCROOT" -maxdepth 1 -type f -name '*.jsp' | wc -l | tr -d ' ')" \
  "$({ find "$DOCROOT" -maxdepth 1 -type f -name '*.jsp' -print0 | xargs -0 cat; } | wc -l | tr -d ' ')"
for loc in ja zh; do
  printf '| %s | %s | %s |\n' "\`$loc/\`" \
    "$(count_files '*.jsp' "$DOCROOT/$loc")" "$(count_lines '*.jsp' "$DOCROOT/$loc")"
done
printf '| **Total** | %s | %s |\n' "$(count_files '*.jsp' "$DOCROOT")" "$(count_lines '*.jsp' "$DOCROOT")"
echo

echo "## API surface"
echo
echo "Number of Java files in scope that import each API. This is the size of"
echo "the change, per technology, that the migration has to absorb."
echo
echo "| API | Files importing it |"
echo "| --- | --- |"
api_row "javax.ejb" "javax\.ejb"
api_row "javax.naming" "javax\.naming"
api_row "javax.servlet (all)" "javax\.servlet"
api_row "javax.servlet.jsp" "javax\.servlet\.jsp"
api_row "java.sql / javax.sql" "java\.sql|javax\.sql"
api_row "javax.xml / org.w3c.dom / org.xml.sax" "javax\.xml|org\.w3c\.dom|org\.xml\.sax"
api_row "java.rmi" "java\.rmi"
api_row "javax.jms" "javax\.jms"
api_row "javax.transaction" "javax\.transaction"
api_row "javax.mail" "javax\.mail"
echo

echo "## Component kinds"
echo
echo "| Kind | Files |"
echo "| --- | --- |"
kind_row "Classes that directly implement \`SessionBean\`" "implements[[:space:]].*SessionBean"
kind_row "Classes that directly implement \`EntityBean\`" "implements[[:space:]].*EntityBean"
kind_row "Message-driven beans" "implements[[:space:]].*MessageDrivenBean"
kind_row "Servlets (\`extends HttpServlet\`)" "extends[[:space:]]+HttpServlet"
kind_row "Servlet filters (\`implements Filter\`)" "implements[[:space:]]+(.*[^a-zA-Z])?Filter([^a-zA-Z]|\$)"
kind_row "JSP tag handlers (\`TagSupport\` / \`BodyTagSupport\`)" "extends[[:space:]]+(Body)?TagSupport"
kind_row "Session listeners" "implements[[:space:]].*HttpSession(Attribute)?Listener"
echo

echo "## Deployment descriptors in scope"
echo
echo "| Item | Count |"
echo "| --- | --- |"
printf '| `ejb-jar.xml` files | %s |\n' "$(count_files 'ejb-jar.xml' "${SCOPE_DIRS[@]}")"
printf '| Session bean declarations | %s |\n' "$(occurrences '<session>' 'ejb-jar.xml' "${SCOPE_DIRS[@]}")"
printf '| Entity bean declarations (shared beans are declared in several descriptors) | %s |\n' "$(occurrences '<entity>' 'ejb-jar.xml' "${SCOPE_DIRS[@]}")"
printf '| Container-managed relationships | %s |\n' "$(occurrences '<ejb-relation>' 'ejb-jar.xml' "${SCOPE_DIRS[@]}")"
printf '| Transaction attributes | %s |\n' "$(occurrences '<trans-attribute>' 'ejb-jar.xml' "${SCOPE_DIRS[@]}")"
printf '| ... of which `Required` | %s |\n' "$(occurrences '<trans-attribute>Required</trans-attribute>' 'ejb-jar.xml' "${SCOPE_DIRS[@]}")"
printf '| Automated test classes (`*Test*.java`) | %s |\n' "$(count_files '*Test*.java' "$SRC")"
echo

echo "## Out of scope"
echo
echo "| Source tree | Java files |"
echo "| --- | --- |"
for d in $OUT_OF_SCOPE; do
  printf '| `%s` | %s |\n' "$d" "$(count_files '*.java' "$SRC/$d")"
done
